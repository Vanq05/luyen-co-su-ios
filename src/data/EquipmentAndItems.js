export function createArmorPiece(setId, slotId, rarityId = "pham") {
  const set = ARMOR_SETS[setId] ?? ARMOR_SETS.thu_bi_bo;
  const rar = RARITIES[rarityId] ?? RARITIES.pham;
  const slotInfo = ARMOR_SLOTS.find((s) => s.id === slotId) ?? ARMOR_SLOTS[0];
  return {
    uid: `eq_${Date.now().toString(36)}_${Math.random().toString(36).slice(2, 6)}`,
    setId: set.id,
    slotId: slotInfo.id,
    rarity: rar.id,
    rarityColor: rar.color,
    name: `${slotInfo.name} · ${set.name}`,
    enhanceLevel: 0,
    hpBonus: Math.round(set.baseHp * rar.mult),
    dmgBonus: Math.round(set.baseDmg * rar.mult),
    armorBonus: Number((set.baseArmor * rar.mult).toFixed(3)),
  };
}
