#!/usr/bin/env node
/**
 * Build static web bundle into dist/ ready for Capacitor iOS (`npx cap copy ios`)
 * and local dev server:
 * 1. Embed `public/assets/manifest.json` + all 36 sprite sheet JSONs into `src/generated/embeddedAssets.js`
 *    so iOS WKWebView (`capacitor://localhost`) makes ZERO local `fetch()` calls.
 * 2. Bundle ES modules via `esbuild` into a single classic script `dist/app.js` (IIFE, es2019/ios14)
 *    so iOS WKWebView never hits ESM module or CORS restrictions.
 * 3. Copy `src/ui/styles.css` -> `dist/styles.css`, copy PNG assets -> `dist/assets/`,
 *    and emit diagnostic-ready `dist/index.html`.
 */

import {
  copyFileSync,
  existsSync,
  mkdirSync,
  readdirSync,
  readFileSync,
  rmSync,
  statSync,
  writeFileSync,
} from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { buildSync } from "esbuild";

const ROOT = resolve(fileURLToPath(new URL("..", import.meta.url)));
const DIST = join(ROOT, "dist");
const PUBLIC_DIR = join(ROOT, "public");
const GENERATED_DIR = join(ROOT, "src", "generated");

function generateEmbeddedAssets() {
  const manifestPath = join(PUBLIC_DIR, "assets", "manifest.json");
  if (!existsSync(manifestPath)) {
    throw new Error(`Không tìm thấy ${manifestPath}`);
  }
  const manifest = JSON.parse(readFileSync(manifestPath, "utf8"));
  const sheets = {};

  for (const [key, item] of Object.entries(manifest.assets ?? {})) {
    const relJson = String(item.json ?? "").replace(/^\.\//, "");
    const jsonPath = join(PUBLIC_DIR, relJson);
    if (!existsSync(jsonPath)) {
      throw new Error(`Thiếu sprite sheet JSON cho "${key}": ${jsonPath}`);
    }
    sheets[key] = JSON.parse(readFileSync(jsonPath, "utf8"));
  }

  mkdirSync(GENERATED_DIR, { recursive: true });
  const code =
    `// Auto-generated by scripts/build-web.mjs — DO NOT EDIT MANUALLY.\n` +
    `export const EMBEDDED_MANIFEST = ${JSON.stringify(manifest)};\n` +
    `export const EMBEDDED_SHEETS = ${JSON.stringify(sheets)};\n`;

  const outFile = join(GENERATED_DIR, "embeddedAssets.js");
  writeFileSync(outFile, code, "utf8");
  return Object.keys(sheets).length;
}

function copyPngAssets(srcDir, dstDir) {
  if (!existsSync(srcDir)) return 0;
  mkdirSync(dstDir, { recursive: true });
  let count = 0;
  for (const entry of readdirSync(srcDir)) {
    const full = join(srcDir, entry);
    const out = join(dstDir, entry);
    if (statSync(full).isDirectory()) {
      count += copyPngAssets(full, out);
    } else if (entry.toLowerCase().endsWith(".png")) {
      mkdirSync(dirname(out), { recursive: true });
      copyFileSync(full, out);
      count += 1;
    }
  }
  return count;
}

function emitIndexHtml() {
  const html = `<!DOCTYPE html>
<html lang="vi">
  <head>
    <meta charset="UTF-8" />
    <meta
      name="viewport"
      content="width=device-width, initial-scale=1.0, maximum-scale=1.0, user-scalable=no, viewport-fit=cover"
    />
    <meta name="apple-mobile-web-app-capable" content="yes" />
    <meta name="apple-mobile-web-app-status-bar-style" content="black-translucent" />
    <meta name="theme-color" content="#0b0d0a" />
    <title>Cổ Chân Nhân: Cổ Tiên Lộ — Khai Khiếu · Luyện Cổ · Độc Bộ Ngũ Vực</title>
    <link rel="preconnect" href="https://fonts.googleapis.com" />
    <link rel="preconnect" href="https://fonts.gstatic.com" crossorigin />
    <link
      href="https://fonts.googleapis.com/css2?family=Be+Vietnam+Pro:wght@500;600;700;800&family=Pixelify+Sans:wght@500;600;700&family=VT323&display=swap"
      rel="stylesheet"
    />
    <link rel="stylesheet" href="./styles.css" />
  </head>
  <body>
    <main id="game-root">
      <canvas id="game-canvas" width="960" height="540"></canvas>
      <div id="hud-layer"></div>
      <div id="minigame-root"></div>
      <div id="fusion-modal-root"></div>
      <div id="account-modal-root"></div>
      <div id="overlay-screen" class="is-open">
        <div class="overlay-card gate-boot-card">
          <div class="overlay-badge">CỔ CHÂN NHÂN · FAN GAME PHI THƯƠNG MẠI</div>
          <h1 class="overlay-title">CỔ TIÊN LỘ</h1>
          <p id="boot-status" class="overlay-sub">Đang mở cổng Nam Cương...</p>
          <pre id="boot-diag" class="boot-diag hidden"></pre>
        </div>
      </div>
    </main>

    <script>
      (function () {
        var shown = false;
        function showBootError(label, err) {
          var status = document.getElementById("boot-status");
          var diag = document.getElementById("boot-diag");
          if (status && !shown) {
            status.textContent = "Lỗi khởi động (" + label + "). Vui lòng chụp màn hình này:";
            shown = true;
          }
          if (diag) {
            diag.classList.remove("hidden");
            var msg = err && (err.stack || err.message) ? (err.stack || err.message) : String(err);
            diag.textContent += "[" + label + "] " + msg + "\\n";
          }
        }
        window.addEventListener("error", function (e) {
          showBootError("error", (e && (e.error || e.message)) || "Unknown error");
        });
        window.addEventListener("unhandledrejection", function (e) {
          showBootError("promise", e ? e.reason : "Unhandled rejection");
        });
      })();
    </script>
    <script defer src="./app.js"></script>
  </body>
</html>
`;
  writeFileSync(join(DIST, "index.html"), html, "utf8");
}

function countFiles(dir) {
  let count = 0;
  for (const entry of readdirSync(dir)) {
    const full = join(dir, entry);
    if (statSync(full).isDirectory()) {
      count += countFiles(full);
    } else {
      count += 1;
    }
  }
  return count;
}

const sheetCount = generateEmbeddedAssets();

if (existsSync(DIST)) {
  rmSync(DIST, { recursive: true, force: true });
}
mkdirSync(DIST, { recursive: true });

buildSync({
  entryPoints: [join(ROOT, "src", "main.js")],
  outfile: join(DIST, "app.js"),
  bundle: true,
  format: "iife",
  platform: "browser",
  target: ["es2020"],
  minify: false,
  sourcemap: false,
  logLevel: "info",
});

copyFileSync(join(ROOT, "src", "ui", "styles.css"), join(DIST, "styles.css"));
const pngCount = copyPngAssets(join(PUBLIC_DIR, "assets"), join(DIST, "assets"));
emitIndexHtml();

const total = countFiles(DIST);
console.log(
  `[build-web] Embedded ${sheetCount} sheets, bundled dist/app.js (IIFE es2020), copied ${pngCount} PNGs (${total} files total in ${DIST})`
);
